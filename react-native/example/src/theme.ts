export function palette(dark: boolean) {
  return {
    background: dark ? '#000000' : '#F2F2F7',
    card: dark ? '#1C1C1E' : '#FFFFFF',
    text: dark ? '#FFFFFF' : '#000000',
    secondaryText: dark ? '#98989F' : '#6C6C70',
    separator: dark ? '#38383A' : '#C6C6C8',
    primary: '#7C3AED',
  };
}
